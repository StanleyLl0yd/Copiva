import AppKit
import CopivaCore

/// All pasteboard access stays on the main actor. No clipboard contents are logged.
@MainActor
public final class ClipboardMonitor {
    static let selfWriteType = NSPasteboard.PasteboardType("io.github.StanleyLl0yd.Copiva.generated")
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        selfWriteType,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.agilebits.onepassword")
    ]

    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    public private(set) var isRecording = false
    public private(set) var lastWriteChangeCount: Int?

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    public func setRecording(_ enabled: Bool) {
        // Never import what was already on the clipboard before consent/resume.
        lastChangeCount = pasteboard.changeCount
        isRecording = enabled
    }

    public func readNewText(sourceBundleID: String?, excludedBundleIDs: Set<String>) -> String? {
        guard isRecording else { return nil }
        let observedCount = pasteboard.changeCount
        guard observedCount != lastChangeCount else { return nil }
        lastChangeCount = observedCount
        guard sourceBundleID.map({ !excludedBundleIDs.contains($0) }) ?? excludedBundleIDs.isEmpty,
              let items = pasteboard.pasteboardItems, items.count == 1,
              let item = items.first else { return nil }
        let types = Set(item.types)
        guard types.isDisjoint(with: Self.ignoredTypes),
              !types.contains(.fileURL), !types.contains(.init("NSFilenamesPboardType")),
              types.contains(.string),
              let data = item.data(forType: .string),
              !data.isEmpty, data.count <= HistoryStore.maximumTextBytes,
              let text = String(data: data, encoding: .utf8),
              pasteboard.changeCount == observedCount else { return nil }
        return text
    }

    /// Only an explicit Copy/Paste action may replace the user's current clipboard.
    @discardableResult
    public func copyText(_ text: String) -> Bool {
        lastWriteChangeCount = nil
        guard !text.isEmpty, text.utf8.count <= HistoryStore.maximumTextBytes else { return false }
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string),
              item.setData(Data(), forType: Self.selfWriteType),
              item.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType")) else {
            return false
        }
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else { return false }
        lastWriteChangeCount = pasteboard.changeCount
        return true
    }
}
